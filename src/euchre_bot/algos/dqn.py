"""DQN (Deep Q-Network), with the Double-DQN target.

DQN is the odd one out in this project: it is *value-based* and *off-policy*,
where REINFORCE/A2C/PPO are policy-gradient methods. It covers the other half of
the RL map -- replay buffers, target networks, and bootstrapped TD targets.

The idea
--------
Learn an action-value function Q(s, a) and act greedily (with epsilon-greedy
exploration) with respect to it. Train Q to satisfy the Bellman equation using a
slowly-updated *target network* for stability. We use the Double-DQN target,
which picks a' with the online net and scores it with the target net to curb
max-operator overestimation:

    a*  = argmax_{a'} Q_online(s_{t+1}, a')
    y_t = r_t + gamma * Q_target(s_{t+1}, a*)   (0 if s_t was terminal)
    loss = SmoothL1( Q(s_t, a_t), y_t )

Key machinery (different from the policy-gradient agents)
---------------------------------------------------------
* **Replay buffer**: a fixed-size ring of (s, a, r, s', done, next_mask) arrays,
  sampled uniformly to break temporal correlation. The training loop hands us
  whole trajectories; ``learn`` pushes their transitions in, then updates.
* **Next-state pairing**: the base Transition stores no next-state, so we pair
  consecutive transitions *within a seat's trajectory*. From one seat's point of
  view, the other three seats' moves in between are just environment dynamics,
  so s_{t+1} is that seat's next decision point.
* **Target network**: a periodically-copied clone of Q used to compute y_t.
* **Epsilon-greedy**: `act` returns a random legal action with prob epsilon,
  else argmax Q over **legal** actions.

Masking with Q-values
---------------------
* In `act`, the argmax is over legal actions only -- Q of illegal actions is
  set to -inf first.
* In the **TD target**, the argmax over a' is restricted to actions legal in s'
  (hence ``next_mask``). Forgetting this lets the target leak value through
  illegal actions and quietly wrecks training. Terminal rows get an all-ones
  dummy mask; their bootstrap term is multiplied by zero anyway.

A caution on self-play + off-policy
-----------------------------------
The replay buffer holds transitions generated by *old* versions of the policy
(and old opponents). In self-play that staleness is more pronounced than for the
on-policy methods. Smaller buffers, target updates, and patience help.

References
----------
* Mnih et al. (2015), "Human-level control through deep RL" (Nature DQN).
* van Hasselt et al. (2016), Double DQN.
* ``docs/implementing_algorithms.md``.
"""

from __future__ import annotations

import copy

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

from ..agents.base import Agent, Trajectory
from ..env.euchre_env import EuchreEnv


class _ReplayBuffer:
    """Fixed-capacity ring buffer of transitions stored as preallocated arrays."""

    def __init__(self, capacity: int, obs_dim: int, n_actions: int) -> None:
        self.capacity = capacity
        self.obs = np.zeros((capacity, obs_dim), dtype=np.float32)
        self.actions = np.zeros(capacity, dtype=np.int64)
        self.rewards = np.zeros(capacity, dtype=np.float32)
        self.next_obs = np.zeros((capacity, obs_dim), dtype=np.float32)
        self.next_masks = np.zeros((capacity, n_actions), dtype=np.bool_)
        self.dones = np.zeros(capacity, dtype=np.float32)
        self.pos = 0
        self.size = 0

    def push(self, obs, action, reward, next_obs, next_mask, done) -> None:
        i = self.pos
        self.obs[i] = obs
        self.actions[i] = action
        self.rewards[i] = reward
        self.next_obs[i] = next_obs
        self.next_masks[i] = next_mask
        self.dones[i] = done
        self.pos = (self.pos + 1) % self.capacity
        self.size = min(self.size + 1, self.capacity)

    def sample(self, batch_size: int, rng: np.random.Generator) -> tuple[np.ndarray, ...]:
        idx = rng.integers(0, self.size, size=batch_size)
        return (self.obs[idx], self.actions[idx], self.rewards[idx],
                self.next_obs[idx], self.next_masks[idx], self.dones[idx])

    def __len__(self) -> int:
        return self.size


class DQNAgent(Agent):
    def __init__(
        self,
        obs_dim: int = EuchreEnv.observation_dim,
        n_actions: int = EuchreEnv.num_actions,
        hidden_dim: int = 256,
        lr: float = 1e-4,
        gamma: float = 0.99,
        buffer_size: int = 50_000,
        batch_size: int = 256,
        target_update_every: int = 500,
        epsilon_start: float = 1.0,
        epsilon_end: float = 0.05,
        epsilon_decay_steps: int = 200_000,
        learning_starts: int = 2_000,
        updates_per_learn: int = 8,
        max_grad_norm: float = 10.0,
        device: str = "cpu",
        seed: int | None = None,
    ) -> None:
        self.gamma = gamma
        self.batch_size = batch_size
        self.target_update_every = target_update_every
        self.epsilon_start = epsilon_start
        self.epsilon_end = epsilon_end
        self.epsilon_decay_steps = epsilon_decay_steps
        self.learning_starts = learning_starts
        self.updates_per_learn = updates_per_learn
        self.max_grad_norm = max_grad_norm
        self.device = torch.device(device)
        self.n_actions = n_actions
        if seed is not None:
            torch.manual_seed(seed)
        self.rng = np.random.default_rng(seed)

        self.q_net = nn.Sequential(
            nn.Linear(obs_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, n_actions),
        ).to(self.device)
        self.target_net = copy.deepcopy(self.q_net).eval()
        for p in self.target_net.parameters():
            p.requires_grad_(False)

        self.optimizer = torch.optim.Adam(self.q_net.parameters(), lr=lr)
        self.buffer = _ReplayBuffer(buffer_size, obs_dim, n_actions)
        self.act_steps = 0      # exploratory act() calls, drives the epsilon schedule
        self.grad_steps = 0     # optimizer steps, drives target-network syncs

    # ------------------------------------------------------------------ #
    # Acting
    # ------------------------------------------------------------------ #

    @property
    def epsilon(self) -> float:
        frac = min(1.0, self.act_steps / self.epsilon_decay_steps)
        return self.epsilon_start + frac * (self.epsilon_end - self.epsilon_start)

    def act(self, observation, action_mask, info=None, *, deterministic=False) -> int:
        if not deterministic:
            explore = self.rng.random() < self.epsilon
            self.act_steps += 1
            if explore:
                return int(self.rng.choice(np.flatnonzero(action_mask)))
        with torch.no_grad():
            obs = torch.as_tensor(observation, dtype=torch.float32, device=self.device)
            mask = torch.as_tensor(action_mask, dtype=torch.bool, device=self.device)
            q = self.q_net(obs).masked_fill(~mask, float("-inf"))
            return int(torch.argmax(q).item())

    # ------------------------------------------------------------------ #
    # Learning
    # ------------------------------------------------------------------ #

    def _push_trajectory(self, trajectory: Trajectory) -> None:
        dummy_mask = np.ones(self.n_actions, dtype=np.bool_)
        for i, transition in enumerate(trajectory):
            if i + 1 < len(trajectory):
                nxt = trajectory[i + 1]
                next_obs, next_mask, done = nxt.observation, nxt.action_mask > 0, 0.0
            else:
                next_obs, next_mask, done = transition.observation, dummy_mask, 1.0
            self.buffer.push(transition.observation, transition.action, transition.reward,
                             next_obs, next_mask, done)

    def learn(self, batch: list[Trajectory]) -> dict[str, float]:
        for trajectory in batch:
            if trajectory:
                self._push_trajectory(trajectory)

        metrics = {"epsilon": self.epsilon, "buffer_size": float(len(self.buffer))}
        if len(self.buffer) < max(self.learning_starts, self.batch_size):
            return metrics

        losses: list[float] = []
        q_means: list[float] = []
        for _ in range(self.updates_per_learn):
            obs, actions, rewards, next_obs, next_masks, dones = (
                torch.as_tensor(x, device=self.device)
                for x in self.buffer.sample(self.batch_size, self.rng)
            )

            q_taken = self.q_net(obs).gather(1, actions.unsqueeze(1)).squeeze(1)
            with torch.no_grad():
                # Double DQN: online net picks the legal next action, target scores it.
                next_q_online = self.q_net(next_obs).masked_fill(~next_masks, float("-inf"))
                next_actions = next_q_online.argmax(dim=1, keepdim=True)
                next_q = self.target_net(next_obs).gather(1, next_actions).squeeze(1)
                targets = rewards + self.gamma * (1.0 - dones) * next_q

            loss = F.smooth_l1_loss(q_taken, targets)
            self.optimizer.zero_grad()
            loss.backward()
            nn.utils.clip_grad_norm_(self.q_net.parameters(), self.max_grad_norm)
            self.optimizer.step()

            self.grad_steps += 1
            if self.grad_steps % self.target_update_every == 0:
                self.target_net.load_state_dict(self.q_net.state_dict())

            losses.append(float(loss.item()))
            q_means.append(float(q_taken.mean().item()))

        metrics.update({"loss": float(np.mean(losses)), "q_mean": float(np.mean(q_means))})
        return metrics

    # ------------------------------------------------------------------ #
    # Persistence
    # ------------------------------------------------------------------ #

    def save(self, path: str) -> None:
        torch.save(self.q_net.state_dict(), path)

    def load(self, path: str) -> None:
        self.q_net.load_state_dict(torch.load(path, map_location=self.device))
        self.target_net.load_state_dict(self.q_net.state_dict())
